import {initializeApp,applicationDefault} from 'firebase-admin/app';
import {getAuth} from 'firebase-admin/auth';
import {createApp} from './app.js';
import {mongoStore} from './store.js';
if(!process.env.MONGODB_URI||!process.env.FIREBASE_PROJECT_ID)throw new Error('MONGODB_URI and FIREBASE_PROJECT_ID required; see .env.example');
initializeApp({credential:applicationDefault(),projectId:process.env.FIREBASE_PROJECT_ID});
const store=await mongoStore(process.env.MONGODB_URI);
const app=createApp(store,async token=>{const d=await getAuth().verifyIdToken(token,true);return {uid:d.uid,emailVerified:d.email_verified===true,authTime:d.auth_time};});
const server=app.listen(Number(process.env.PORT??8080),process.env.HOST??'127.0.0.1',()=>console.info('FamilyGuard API listening'));
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,()=>server.close(()=>process.exit(0)));
